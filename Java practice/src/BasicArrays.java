public class BasicArrays {
    public static void main(String[] args){
        int[] BasicArrays = {10,40,60,20,90};
        for(int i=0;i<BasicArrays.length;i++){
            System.out.println(BasicArrays[i]);
        }
        System.out.println(BasicArrays[0]);
        System.out.println(BasicArrays[4]);
        System.out.println(BasicArrays.length);
    }
}
